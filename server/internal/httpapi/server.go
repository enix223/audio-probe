type Server struct {
	hub    *hub.Hub
	layout *storage.Layout
	log    *log.Logger
}

func New(h *hub.Hub, layout *storage.Layout, logger *log.Logger) *Server {
	if logger == nil {
		logger = log.Default()
	}
	return &Server{hub: h, layout: layout, log: logger}
}

func (s *Server) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("/api/v1/health", s.handleHealth)
	mux.HandleFunc("/api/v1/devices", s.handleDevices)
	mux.HandleFunc("/api/v1/devices/", s.handleDeviceCommand)
	mux.HandleFunc("/api/v1/captures", s.handleCaptures)
	mux.HandleFunc("/api/v1/captures/", s.handleCapture)
	mux.HandleFunc("/api/v1/tests", s.handleTests)
	mux.Handle("/data/", http.StripPrefix("/data/", http.FileServer(http.Dir(s.layout.Root))))

	dist, err := fs.Sub(web.Dist, "dist")
	if err != nil {
		// The embed is generated by `scripts/build_web.sh`; keep the API usable
		// if the frontend was stripped from a custom build.
		s.log.Printf("frontend assets unavailable: %v", err)
		mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
			http.Error(w, "frontend not built; run scripts/build_web.sh", http.StatusNotFound)
		})
	} else {
		mux.Handle("/", spaHandler(dist))
	}
	return withCORS(mux)
}

// withCORS lets the Vite dev server (port 5173) call the API directly when a
// developer does not use the Vite proxy. Production serves the SPA from the
// same origin, so CORS is irrelevant there.
func withCORS(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(r.URL.Path, "/api/") || strings.HasPrefix(r.URL.Path, "/data/") {
			w.Header().Set("Access-Control-Allow-Origin", "*")
			w.Header().Set("Access-Control-Allow-Headers", "Content-Type, Authorization")
			w.Header().Set("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
			if r.Method == http.MethodOptions {
				w.WriteHeader(http.StatusNoContent)
				return
			}
		}
		next.ServeHTTP(w, r)
	})
}

// spaHandler serves the React build and falls back to index.html for client
// routes. API and /data/ paths never reach it (the mux routes are more
// specific).
func spaHandler(dist fs.FS) http.Handler {
	fileServer := http.FileServer(http.FS(dist))
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(r.URL.Path, "/api/") || strings.HasPrefix(r.URL.Path, "/data/") {
			http.NotFound(w, r)
			return
		}
		name := strings.TrimPrefix(filepath.ToSlash(filepath.Clean(r.URL.Path)), "/")
		if name == "" || name == "." {
			name = "index.html"
		}
		if f, err := dist.Open(name); err == nil {
			_ = f.Close()
			fileServer.ServeHTTP(w, r)
			return
		}
		data, err := fs.ReadFile(dist, "index.html")
		if err != nil {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Cache-Control", "no-cache")
		_, _ = w.Write(data)
	})
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func (s *Server) handleHealth(w http.ResponseWriter, r *http.Request) {
	writeJSON(w, http.StatusOK, map[string]any{
		"ok": true, "time": time.Now().UTC(), "devices": len(s.hub.List()),
	})
}

func (s *Server) handleDevices(w http.ResponseWriter, r *http.Request) {
	list := make([]map[string]any, 0, len(s.hub.List()))
	for _, sess := range s.hub.List() {
		list = append(list, sess.Snapshot())
	}
	writeJSON(w, http.StatusOK, map[string]any{"devices": list})
}

func (s *Server) handleCaptures(w http.ResponseWriter, r *http.Request) {
	caps, err := s.layout.ListCaptures()
	if err != nil {
		writeJSON(w, http.StatusInternalServerError, map[string]any{"error": err.Error()})
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"captures": caps})
}

func validPathPart(p string) bool {
	if p == "" || p == "." || p == ".." || len(p) > 128 {
		return false
	}
	for _, r := range p {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') ||
			(r >= '0' && r <= '9') || r == '-' || r == '_' || r == '.' {
			continue
		}
		return false
	}
	return true
}

type segmentEntry struct {
	ID          uint32          `json:"id"`
	HasAudio    bool            `json:"has_audio"`
	HasPackets  bool            `json:"has_packets"`
	HasWaveform bool            `json:"has_waveform"`
	HasSpectrum bool            `json:"has_spectrum"`
	Metrics     json.RawMessage `json:"metrics,omitempty"`
	Meta        json.RawMessage `json:"meta,omitempty"`
}

func readOptional(path string) json.RawMessage {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	return json.RawMessage(data)
}

func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func (s *Server) listSegments(w http.ResponseWriter, id, dir string) {
	entries, err := os.ReadDir(filepath.Join(dir, "segments"))
	if err != nil {
		writeJSON(w, http.StatusOK, map[string]any{"capture_id": id, "segments": []segmentEntry{}})
		return
	}
	out := make([]segmentEntry, 0, len(entries))
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		n, err := strconv.ParseUint(e.Name(), 10, 32)
		if err != nil {
			continue
		}
		segDir := filepath.Join(dir, "segments", e.Name())
		out = append(out, segmentEntry{
			ID:          uint32(n),
			HasAudio:    fileExists(filepath.Join(segDir, "audio.wav")),
			HasPackets:  fileExists(filepath.Join(segDir, "packets.bin")),
			HasWaveform: fileExists(filepath.Join(segDir, "plots", "waveform.png")),
			HasSpectrum: fileExists(filepath.Join(segDir, "plots", "spectrum.png")),
			Metrics:     readOptional(filepath.Join(segDir, "metrics.json")),
			Meta:        readOptional(filepath.Join(segDir, "meta.json")),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	writeJSON(w, http.StatusOK, map[string]any{"capture_id": id, "segments": out})
}

func (s *Server) handleCapture(w http.ResponseWriter, r *http.Request) {
	rest := strings.TrimPrefix(r.URL.Path, "/api/v1/captures/")
	parts := strings.Split(rest, "/")
	for _, p := range parts {
		if !validPathPart(p) {
			writeJSON(w, http.StatusBadRequest, map[string]any{"error": "invalid path"})
			return
		}
	}
	id := parts[0]
	dir, err := s.layout.CaptureDir(id)
	if err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": err.Error()})
		return
	}
	if len(parts) == 1 {
		manifest, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
		if err != nil {
			writeJSON(w, http.StatusNotFound, map[string]any{"error": "capture not found"})
			return
		}
		var m any
		if json.Unmarshal(manifest, &m) != nil {
			m = string(manifest)
		}
		segs, _ := os.ReadDir(filepath.Join(dir, "segments"))
		segIDs := make([]string, 0, len(segs))
		for _, e := range segs {
			if e.IsDir() {
				segIDs = append(segIDs, e.Name())
			}
		}
		writeJSON(w, http.StatusOK, map[string]any{
			"id": id, "manifest": m, "segments": segIDs,
			"report":  "/data/captures/" + id + "/report.html",
			"summary": "/data/captures/" + id + "/summary.csv",
		})
		return
	}
	if len(parts) == 2 && parts[1] == "segments" {
		s.listSegments(w, id, dir)
		return
	}

	// Serve a known file (summary.csv, report.html, manifest.json) or a
	// segment sidecar (segments/<id>/audio.wav, metrics.json, frames.csv, ...).
	path := filepath.Join(append([]string{dir}, parts[1:]...)...)
	info, err := os.Stat(path)
	if err != nil || info.IsDir() {
		writeJSON(w, http.StatusNotFound, map[string]any{"error": "file not found"})
		return
	}
	switch strings.ToLower(filepath.Ext(path)) {
	case ".wav":
		w.Header().Set("Content-Type", "audio/wav")
	case ".json":
		w.Header().Set("Content-Type", "application/json")
	case ".csv":
		w.Header().Set("Content-Type", "text/csv")
	case ".html":
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
	case ".png":
		w.Header().Set("Content-Type", "image/png")
	case ".bin":
		w.Header().Set("Content-Type", "application/octet-stream")
	}
	http.ServeFile(w, r, path)
}

func (s *Server) handleDeviceCommand(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		writeJSON(w, http.StatusMethodNotAllowed, map[string]any{"error": "POST required"})
		return
	}
	rest := strings.TrimPrefix(r.URL.Path, "/api/v1/devices/")
	parts := strings.Split(rest, "/")
	if len(parts) != 2 || parts[1] != "commands" || !validPathPart(parts[0]) {
		writeJSON(w, http.StatusNotFound, map[string]any{"error": "not found"})
		return
	}
	deviceID := parts[0]
	sess := s.hub.Get(deviceID)
	if sess == nil {
		writeJSON(w, http.StatusNotFound, map[string]any{"error": "device not connected"})
		return
	}
	var cmd map[string]any
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&cmd); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": protocol.ErrBadMessage, "message": err.Error()})
		return
	}
	resp, err := sess.SendCommand(cmd, 5*time.Second)
	if err != nil {
		status := http.StatusBadGateway
		code := "command_failed"
		switch {
		case errors.Is(err, session.ErrControlOwnedByMQTT):
			status = http.StatusConflict
			code = protocol.ErrControlOwnedByMQTT
		case errors.Is(err, session.ErrCommandTimeout):
			status = http.StatusAccepted
			code = "pending"
		}
		writeJSON(w, status, map[string]any{"error": code, "message": err.Error()})
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write(resp)
}

func (s *Server) handleTests(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		writeJSON(w, http.StatusMethodNotAllowed, map[string]any{"error": "POST required"})
		return
	}
	var req struct {
		DeviceID      string    `json:"device_id"`
		Kind          string    `json:"kind"`
		ToneID        string    `json:"tone_id"`
		Waveform      string    `json:"waveform"`
		FrequencyHz   float64   `json:"frequency_hz"`
		AmplitudeDBFS float64   `json:"amplitude_dbfs"`
		DurationMS    int       `json:"duration_ms"`
		FadeMS        int       `json:"fade_ms"`
		SpeakerVolume int       `json:"speaker_volume"`
		Capture       bool      `json:"capture"`
		Label         string    `json:"label"`
		GainsDB       []float64 `json:"gains_db"`
	}
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&req); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": protocol.ErrBadMessage})
		return
	}
	sess := s.findDevice(req.DeviceID)
	if sess == nil {
		writeJSON(w, http.StatusNotFound, map[string]any{"error": "device not connected"})
		return
	}
	kind := req.Kind
	if kind == "" {
		kind = "tone"
	}
	if kind != "tone" {
		if sess.Control().Owner == "mqtt" && !sess.Control().AllowWSCaptureControl {
			writeJSON(w, http.StatusConflict, map[string]any{
				"error":   protocol.ErrControlOwnedByMQTT,
				"message": "sweeps need start/stop, which MQTT owns",
			})
			return
		}
		writeJSON(w, http.StatusNotImplemented, map[string]any{
			"error":   protocol.ErrUnsupportedFeature,
			"message": "server-orchestrated sweeps are not implemented yet; use a tone test on an active capture",
		})
		return
	}
	if req.ToneID == "" {
		req.ToneID = "tone-1k"
	}
	if req.Waveform == "" {
		req.Waveform = "sine"
	}
	if req.FrequencyHz == 0 {
		req.FrequencyHz = 1000
	}
	if req.AmplitudeDBFS == 0 {
		req.AmplitudeDBFS = -6
	}
	if req.DurationMS == 0 {
		req.DurationMS = 3000
	}
	if req.FadeMS == 0 {
		req.FadeMS = 20
	}
	cmd := map[string]any{
		"type": "test_tone", "tone_id": req.ToneID, "waveform": req.Waveform,
		"frequency_hz": req.FrequencyHz, "amplitude_dbfs": req.AmplitudeDBFS,
		"duration_ms": req.DurationMS, "fade_ms": req.FadeMS,
		"speaker_volume": req.SpeakerVolume, "capture": req.Capture,
		"loopback": false, "label": req.Label,
	}
	timeout := time.Duration(req.DurationMS+5000) * time.Millisecond
	resp, err := sess.SendCommand(cmd, timeout)
	if err != nil {
		status := http.StatusBadGateway
		if errors.Is(err, session.ErrControlOwnedByMQTT) {
			status = http.StatusConflict
		} else if errors.Is(err, session.ErrCommandTimeout) {
			status = http.StatusAccepted
		}
		writeJSON(w, status, map[string]any{"error": "test_failed", "message": err.Error()})
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write(resp)
}

func (s *Server) findDevice(id string) *session.Session {
	if id != "" {
		return s.hub.Get(id)
	}
	list := s.hub.List()
	if len(list) == 1 {
		return list[0]
	}
	return nil
}
